#!/usr/bin/env python3
"""Write fixtures/core.txt: inputs and Python erploc outputs for the erploc-core differential tests.
Record: <tag> <name> <rows> <cols> <values...> (repr, round-trip exact). Set ERPLOC_PY_ROOT to the directory that contains the `erploc` Python package.
Case names start with the module prefix (erp_, rot_, lie_, mk_, jac_)."""
import os
import sys
import numpy as np

REPO = os.environ.get('ERPLOC_PY_ROOT', os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))  # directory that contains the `erploc` Python package
sys.path.insert(0, REPO)
from erploc import erp, rot, lie, markers, jacobian  # noqa: E402

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'fixtures', 'core.txt')
rng = np.random.default_rng(20261005)
lines = ['# generated by tools/export_core_fixtures.py with numpy ' + np.__version__]
PI = np.pi


def rec(tag, name, a):
    a = np.atleast_2d(np.asarray(a, float))
    lines.append(' '.join([tag, name, str(a.shape[0]), str(a.shape[1])] + [repr(float(x)) for x in a.ravel()]))


def flat(rows):
    return np.array([np.asarray(r, float).ravel() for r in rows])


def unit(v):
    return v / np.linalg.norm(v)


def rand_rot():
    return rot.exp_so3(unit(rng.normal(size=3)) * rng.uniform(0.0, PI - 0.05))


# ---------------------------------------------------------------- erp
for ls in (1, -1):
    cam = erp.ErpCamera(6528, 3264, ls)
    nm = 'erp_px%d' % (ls > 0)
    uv = np.vstack([[[0, 0], [6527, 3263], [3263.5, 1631.5], [0, 3263], [6527, 0], [3264, 1632], [1, 1], [6526, 3262]],
                    np.column_stack([rng.uniform(0, 6527, 16), rng.uniform(0, 3263, 16)])])
    rec('ls', nm, [ls]); rec('uv', nm, uv); rec('lp', nm, erp.px_to_lamphi(uv, cam))
    lp = np.vstack([[[0, 0], [PI, 0], [-PI, 0], [PI, PI / 2], [-PI, -PI / 2], [3 * PI, 0.1], [-4.0, -1.0], [1e-9, 1e-9]],
                    np.column_stack([rng.uniform(-PI, PI, 16), rng.uniform(-PI / 2, PI / 2, 16)])])
    nm2 = 'erp_lp%d' % (ls > 0)
    rec('ls', nm2, [ls]); rec('lp', nm2, lp); rec('uv', nm2, erp.lamphi_to_px(lp, cam))
lp = np.vstack([[[0, 0], [PI, 0], [0, PI / 2], [0, -PI / 2], [PI / 2, 0.3], [-PI / 2, -0.3]],
                np.column_stack([rng.uniform(-PI, PI, 20), rng.uniform(-PI / 2, PI / 2, 20)])])
rec('lp', 'erp_brg', lp); rec('d', 'erp_brg', erp.lamphi_to_bearing(lp))
d = np.vstack([[[1, 0, 0], [0, 1, 0], [-1, 0, 1e-9], [0, 0, 1], [0, 0, -1], [0, 1e-8, 1], [-2, 1e-12, 0.5], [3, -4, 12], [-1.0, -0.0, 1e-9]],
               rng.normal(size=(18, 3)) * rng.uniform(0.1, 10, (18, 1))])
rec('d', 'erp_b2l', d); rec('lp', 'erp_b2l', erp.bearing_to_lamphi(d))
phis = np.deg2rad(np.concatenate([[0, 10, 30, 60, 80, 85, -85, -60], rng.uniform(-85, 85, 14)]))
lams = np.concatenate([[0, 3.1, -3.1, 1.5, -1.5, 0.3, PI - 1e-6, -PI + 1e-6], rng.uniform(-PI, PI, 14)])
dd = erp.lamphi_to_bearing(np.column_stack([lams, phis])) * rng.uniform(0.5, 20, (22, 1))
dd = np.vstack([dd, [[1e-3, 1e-3, 1.0], [-1e-4, 2e-4, -1.0]]])
rec('d', 'erp_dl', dd); rec('J', 'erp_dl', np.array([erp.d_lamphi_d_bearing(dd[i:i + 1])[0].ravel() for i in range(len(dd))]))
x = np.array([0, 1, -1, PI, -PI, 3 * PI, -3 * PI, 2 * PI, -2 * PI, 1e-300, -1e-300, 1e6, -1e6, 1e6 + 0.5, 3.14, -3.14, 7.0, -7.0,
              PI - 1e-12, -PI + 1e-12, 0.5, 100.0, -100.0, 12345.678])
rec('x', 'erp_wrap', x); rec('y', 'erp_wrap', erp.wrap_pi(x))
obs = np.vstack([[[3.1, 0.2], [-3.1, -0.2], [0.0, 1.5], [PI - 1e-9, 0.0], [-PI, 0.5], [3.14, -1.55]],
                 np.column_stack([rng.uniform(-PI, PI, 18), rng.uniform(-1.55, 1.55, 18)])])
pred = np.vstack([[[-3.1, 0.25], [3.1, -0.1], [0.0, 1.4], [-PI + 1e-9, 0.1], [PI, 0.0], [-3.14, -1.5]],
                  np.column_stack([rng.uniform(-PI, PI, 18), rng.uniform(-1.55, 1.55, 18)])])
for mdl, ls in [(m_, s_) for s_ in (1, -1) for m_ in ('tangent', 'pixel')]:
    cam = erp.ErpCamera(6528, 3264, ls)
    r, D = erp.residual_lamphi(obs, pred, cam, mdl)
    nm = 'erp_res_%s_%d' % (mdl, ls > 0)
    rec('ls', nm, [ls]); rec('obs', nm, obs); rec('pred', nm, pred); rec('r', nm, r); rec('D', nm, D)

# ---------------------------------------------------------------- rot
ths = [0, 1e-12, 1e-9, 1e-8 * 0.99, 1e-8 * 1.01, 1e-5, 0.01, 0.5, 1.0, 2.0, 3.0, PI - 1e-3, PI - 1e-9, PI]
ws = [unit(rng.normal(size=3)) * t for t in ths] + [np.array([t, 0, 0]) for t in (0.3, 2.9)] + \
     [np.array([0, t, 0]) for t in (0.3, 2.9)] + [np.array([0, 0, t]) for t in (0.3, 2.9)] + \
     [rng.normal(size=3) for _ in range(6)]
ws = np.array(ws)
rec('w', 'rot_exp', ws); rec('R', 'rot_exp', flat([rot.exp_so3(w) for w in ws]))
Rs = [rot.exp_so3(w) for w in ws if np.linalg.norm(w) < PI - 1e-12]
Rs += [np.diag(v) for v in ([1., -1, -1], [-1., 1, -1], [-1., -1, 1])]
# trace <= 0 branch, each diagonal argmax, near pi about each axis plus generic axes
for ax in range(3):
    for t in (PI - 1e-9, PI - 1e-4, 2.5, 2.2):
        v = np.zeros(3); v[ax] = t
        Rs.append(rot.exp_so3(v))
        v2 = unit(rng.normal(size=3)); v2[ax] += 2.0; v2 = unit(v2) * t
        Rs.append(rot.exp_so3(v2))
Rs += [rand_rot() for _ in range(4)]
rec('R', 'rot_log', flat(Rs)); rec('w', 'rot_log', np.array([rot.log_so3(R) for R in Rs]))
rec('R', 'rot_yaw', flat(Rs)); rec('y', 'rot_yaw', [rot.yaw_of(R) for R in Rs])
ang = np.vstack([[[0, 0, 0], [PI, 0, 0], [0, PI / 2, 0], [0, -PI / 2, 0], [0, 0, PI], [-PI, 0.3, -0.3], [1e6, 0, 0]],
                 np.column_stack([rng.uniform(-PI, PI, 16), rng.uniform(-PI / 2, PI / 2, 16), rng.uniform(-PI, PI, 16)])])
rec('ypr', 'rot_zyx', ang); rec('R', 'rot_zyx', flat([rot.rot_zyx(*a) for a in ang]))

# ---------------------------------------------------------------- lie
lths = [0, 1e-13, 0.05, 0.0999, 0.1001, 1, 3, 1e-12, 1e-14, 0.0999999, 0.1000001, 2.0]
lw = [unit(rng.normal(size=3)) * t for t in lths] + [np.array([t, 0, 0]) for t in lths[2:7]] + \
     [rng.normal(size=3) * 0.5 for _ in range(4)]
lw = np.array(lw)
rec('w', 'lie_jl', lw); rec('J', 'lie_jl', flat([lie.jl_so3(w) for w in lw])); rec('Ji', 'lie_jl', flat([lie.jl_inv_so3(w) for w in lw]))
xis = np.array([np.concatenate([rng.normal(size=3) * rng.uniform(0.1, 5), unit(rng.normal(size=3)) * t]) for t in lths] +
               [np.concatenate([rng.normal(size=3), [0, 0, 0]]), np.zeros(6)] +
               [np.concatenate([rng.normal(size=3), rng.normal(size=3) * 0.7]) for _ in range(8)])
Ts = [lie.exp_se3(xi) for xi in xis]
rec('xi', 'lie_se3', xis); rec('T', 'lie_se3', flat(Ts))
rec('T', 'lie_log', flat(Ts)); rec('xi', 'lie_log', np.array([lie.log_se3(T) for T in Ts]))
rec('T', 'lie_ad', flat(Ts)); rec('Ad', 'lie_ad', flat([lie.adjoint_se3(T) for T in Ts]))

# ---------------------------------------------------------------- markers
As = np.array([0.1, 0.16, 0.5, 1.0, 0.25, 0.3])
mp = rng.uniform(-10, 10, (24, 3)); mR = [rand_rot() for _ in range(24)]; mA = rng.uniform(0.05, 1.5, 24)
mp[0] = 0; mR[0] = np.eye(3); mA[0] = 0.16
rec('p', 'mk_cw', mp); rec('R', 'mk_cw', flat(mR)); rec('A', 'mk_cw', mA)
rec('X', 'mk_cw', flat([markers.corners_world(mp[i], mR[i], mA[i]) for i in range(24)]))
rec('dp', 'mk_dc', flat([markers.d_corners(mR[i], mA[i])[0] for i in range(24)]))
rec('dw', 'mk_dc', flat([markers.d_corners(mR[i], mA[i])[1] for i in range(24)]))
rec('R', 'mk_dc', flat(mR)); rec('A', 'mk_dc', mA)
az = np.concatenate([[0, PI / 2, PI, -PI / 2, 1e-9, 7.0], rng.uniform(-PI, PI, 18)])
up = [markers.upright_pose(i, mp[i], az[i]) for i in range(24)]
rec('p', 'mk_up', mp); rec('az', 'mk_up', az); rec('R', 'mk_up', flat([u.R for u in up]))
# facing pose
fp = rng.uniform(-8, 8, (24, 3)); ft = rng.uniform(-8, 8, (24, 3))
ft[0] = fp[0] + [0, 0, 5]; ft[1] = fp[1] + [0, 0, -5]; ft[2] = fp[2] + [3, 0, 0.2]; ft[3] = fp[3] + [0.1, 0.1, 3]
fpsi = np.concatenate([[0, 0.3, 1.0, 1.2, 0, 0.5], rng.uniform(0, 1.2, 18)])
ftd = rng.uniform(-PI, PI, 24); frl = rng.uniform(-PI, PI, 24); frl[:3] = 0
rec('p', 'mk_fp', fp); rec('target', 'mk_fp', ft); rec('args', 'mk_fp', np.column_stack([fpsi, ftd, frl]))
rec('R', 'mk_fp', flat([markers._facing_pose(0, fp[i], ft[i], fpsi[i], ftd[i], frl[i]).R for i in range(24)]))
# planar PnP: marker in the camera frame at the origin, facing the camera, noise-free and noisy (1e-4 rad)
for noisy in (False, True):
    for i in range(24):
        p = unit(rng.normal(size=3)) * rng.uniform(1.5, 10)
        A = rng.uniform(0.1, 1.0)
        mk = markers._facing_pose(0, p, np.zeros(3), rng.uniform(0, 1.2), rng.uniform(-PI, PI), rng.uniform(-PI, PI))
        X = markers.corners_world(mk.p, mk.R, A)
        dn = X / np.linalg.norm(X, axis=1, keepdims=True)
        if noisy:
            dn = dn + rng.normal(size=(4, 3)) * 1e-4
            dn = dn / np.linalg.norm(dn, axis=1, keepdims=True)
        t, R = markers.planar_pnp(dn, A)
        nm = 'mk_pnp%d_%d' % (noisy, i)
        rec('d', nm, dn); rec('A', nm, [A]); rec('t', nm, t); rec('R', nm, R)

# ---------------------------------------------------------------- jacobian
DOFS = [('z',), ('x', 'y', 'z'), ('z', 'x')]
idx = {'x': 0, 'y': 1, 'z': 2}
for i in range(48):
    A = rng.uniform(0.1, 0.6)
    c = rng.uniform(-3, 3, 3)
    kind = i % 4
    mpos = c + unit(rng.normal(size=3)) * rng.uniform(1.5, 8)
    mrot = rand_rot()
    if kind == 0:            # Euler, generic
        cam = jacobian.CamPose(c=c, yaw=rng.uniform(-PI, PI), roll=rng.uniform(-0.3, 0.3), pitch=rng.uniform(-0.3, 0.3))
    elif kind == 1:          # R_mat
        cam = jacobian.CamPose.from_R(c, rand_rot())
    elif kind == 2:          # Euler near the yaw seam: marker behind the camera
        cam = jacobian.CamPose(c=c, yaw=rng.uniform(-PI, PI), roll=0.1, pitch=-0.1)
        behind = cam.R @ np.array([-1.0, 1e-4 * (1 if i % 8 == 2 else -1), 0.05]) * 4.0
        mpos = c + behind
    else:                    # pole: marker almost straight above/below, pitch near +-pi/2
        cam = jacobian.CamPose(c=c, yaw=rng.uniform(-PI, PI), roll=0.05, pitch=(PI / 2 - 1e-3) * (1 if i % 8 == 3 else -1))
        mpos = c + cam.R @ np.array([1e-3, -2e-3, 3.0 * (1 if i % 8 == 3 else -1)])
        mrot = markers.upright_pose(0, mpos, rng.uniform(-PI, PI)).R
    mk = markers.MarkerPose(id=0, p=mpos, R=mrot)
    dof = DOFS[i % 3]
    nm = 'jac_%d' % i
    rec('c', nm, c)
    if cam.R_mat is None:
        rec('eul', nm, [cam.yaw, cam.roll, cam.pitch])
    else:
        rec('rm', nm, cam.R_mat)
    rec('mp', nm, mpos); rec('mR', nm, mrot); rec('A', nm, [A]); rec('dof', nm, [idx[a] for a in dof])
    X = markers.corners_world(mpos, mrot, A)
    lp, dv = jacobian.project(cam, X)
    rec('X', nm, X); rec('lp', nm, lp); rec('dv', nm, dv)
    rec('pred', nm, jacobian.predict_marker(cam, mk, A))
    Jc, Jm = jacobian.jac_marker(cam, mk, A, dof)
    rec('Jc', nm, Jc); rec('Jm', nm, Jm)

os.makedirs(os.path.dirname(OUT), exist_ok=True)
open(OUT, 'w').write('\n'.join(lines) + '\n')
print('wrote', OUT, len(lines) - 1, 'records')
