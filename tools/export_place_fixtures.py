def occ_margin(c, p, obstacles, eps, gap):
    """smallest |z at a clipped interval end - obstacle height| over this sight line."""
    dz = p[2] - c[2]
    t_end = 1.0 - eps
    if gap > 0.0:
        t_end = min(t_end, 1.0 - gap / max(float(np.linalg.norm(p - c)), 1e-12))
    out = np.inf
    for ob in obstacles:
        for (t0, t1) in segment_inside_intervals(c[:2], p[:2], ob.poly):
            t0 = max(t0, eps); t1 = min(t1, t_end)
            if t1 <= t0:
                continue
            out = min(out, abs(c[2] + t0 * dz - ob.height), abs(c[2] + t1 * dz - ob.height))
    return out


