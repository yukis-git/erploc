def rec_eval(case, tb, spec, sels):
    N = tb.vis.shape[2]
    tl = pl._tau_loo(spec)
    cols = {k: [] for k in ('sigma', 'nvis', 'sloo', 'feas', 'margin', 'pen')}
    k2, k3, gp, ninf = [], [], [], []
    for sel in sels:
        st = pl.evaluate(tb, sel, spec)
        cols['sigma'].append(st.sigma); cols['nvis'].append(st.n_vis); cols['sloo'].append(st.sigma_loo)
        cols['feas'].append(st.feasible.astype(float)); cols['margin'].append(st.margin)
        cols['pen'].append(pl.penalty_of(st, spec))
        k2.append(pl._key2(st, spec)); k3.append(pl._key3(st, spec))
        gp.append([np.min(np.abs(st.sigma - spec.tau) / spec.tau), np.min(np.abs(st.sigma_loo - tl) / tl)])
        ninf.append(int((~st.feasible).sum()))
    rec('sel', case, pad([list(s) for s in sels], max(N, 1)))
    for k, v in cols.items():
        rec(k, case, np.array(v))
