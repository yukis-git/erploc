def pad(rows, w, fill=-1.0):
    out = np.full((len(rows), w), fill)
    for i, r in enumerate(rows):
        out[i, :len(r)] = r
    return out


def ob_rows(obstacles):
    return np.array([[i, x, y, ob.height] for i, ob in enumerate(obstacles) for x, y in np.asarray(ob.poly, float)]).reshape(-1, 4)


def sec_rows(sectors):
    return np.array([[s.lam_min, s.lam_max, s.phi_min, s.phi_max] for s in sectors], float).reshape(-1, 4)


def mk_rows(mks):
    return np.array([[mk.id, *mk.p, *np.asarray(mk.R, float).ravel()] for mk in mks]).reshape(-1, 13)


