def near_int_rect(s):
    """x1 = x0 + s/2 + m s as floats: (x1-x0-s/2)/s is within 1e-12 of an integer (not necessarily equal)."""
    for m in range(5, 40):
        x1 = m * s + s / 2
        q = (x1 - 0.0 - s / 2) / s
        if 0 < abs(q - round(q)) < 1e-12 or (q == round(q) and m > 30):
            return x1, q
    return 3.05, (3.05 - 0.05) / 0.1


