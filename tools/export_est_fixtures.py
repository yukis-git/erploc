# ---------------------------------------------------------------- per-corner masks and sigma scales (cases ms_*)
# `cm` record of a case: rows (f, id, mask x4 (0/1), scale x4) aligned with the `obs` rows. Masked uv are exported as NaN
# (and Python runs on the NaN uv), so a Rust read of a masked corner cannot pass unnoticed. Masks come from their own
# generators (seed MS_SEED + k), so the records above are unchanged.
MS_SEED = 20261009


def rec_cm(name, frames):
    rows = []
    for f, fr in enumerate(frames):
        for ob in fr:
            m = np.ones(4) if ob.corner_mask is None else np.asarray(ob.corner_mask, float)
            sc = np.ones(4) if ob.corner_sigma_scale is None else np.asarray(ob.corner_sigma_scale, float)
            rows.append([f, ob.id, *m, *sc])
    rec('cm', name, np.array(rows).reshape(-1, 10))


def masked_frames(frames, rg, p_part=0.5, p_scale=0.7, forced=()):
    """Random masks (at most one invalid corner, so >= 3 valid) and scales in [1, 2.5]; `forced` = (f, i, mask) overrides."""
    out = []
    for fr in frames:
        new = []
        for ob in fr:
            m = np.ones(4, dtype=bool)
            if rg.random() < p_part:
                m[rg.integers(0, 4)] = False
            sc = rg.uniform(1.0, 2.5, size=4) if rg.random() < p_scale else np.ones(4)
            new.append(Observation(id=ob.id, uv=ob.uv, corner_mask=m, corner_sigma_scale=sc))
        out.append(new)
    for f, i, mm in forced:
        ob = out[f][i]
        out[f][i] = Observation(id=ob.id, uv=ob.uv, corner_mask=np.array(mm, dtype=bool),
                                corner_sigma_scale=ob.corner_sigma_scale)
    return out


def nanify(frames):
    out = []
    for fr in frames:
        new = []
        for ob in fr:
            uv = np.array(ob.uv, float)
            if ob.corner_mask is not None:
                uv[~np.asarray(ob.corner_mask, dtype=bool)] = np.nan
            new.append(Observation(id=ob.id, uv=uv, corner_mask=ob.corner_mask, corner_sigma_scale=ob.corner_sigma_scale))
        out.append(new)
    return out


def n_masked(frames):
    return sum(int(np.count_nonzero(~np.asarray(ob.corner_mask, dtype=bool))) for fr in frames for ob in fr
               if ob.corner_mask is not None)


