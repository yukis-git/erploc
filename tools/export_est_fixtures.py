def ms_scene(seed, traj, nf, tilt, nseed, mseed, forced=(), single=()):
    """Noisy render of a b_scene, masked; `single` = ((f, [i...]),) keeps only those observations of frame f."""
    mks, cams, _ = b_scene(seed, traj, nf, tilt)
    frames = zero_gt(None, cams, mks, True, nseed)
    frames = masked_frames(frames, np.random.default_rng(mseed), forced=forced)
    for f, keep in single:
        frames[f] = [frames[f][i] for i in keep]
    return mks, cams, frames


