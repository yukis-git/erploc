def rec(tag, name, a):
    a = np.asarray(a, float)
    a = a.reshape(1, 1) if a.ndim == 0 else (a.reshape(1, -1) if a.ndim == 1 else a)
    lines.append(' '.join([tag, name, str(a.shape[0]), str(a.shape[1])] + [repr(float(x)) for x in a.ravel()]))


class Rec:
    """numpy Generator proxy that records every draw in call order."""

    def __init__(self, seed):
        self.g = np.random.default_rng(seed)
        self.draws = []

    def uniform(self, low=0.0, high=1.0, size=None):
        v = self.g.uniform(low, high, size)
        for x in np.atleast_1d(v).ravel():
            self.draws.append((0.0, float(x)))
        return v

    def normal(self, loc=0.0, scale=1.0, size=None):
        z = self.g.standard_normal(size)
        for x in np.atleast_1d(z).ravel():
            self.draws.append((1.0, float(x)))
        return loc + scale * z

    def dump(self, name):
        a = np.array(self.draws, float).reshape(-1, 2)
        lines.append(' '.join(['draws', name, str(a.shape[0]), '2'] + [repr(float(x)) for x in a.ravel()]))


def cam_row(c):
    return [*np.asarray(c.c, float).ravel(), c.yaw, c.roll, c.pitch]


def mk_rows(mks):
    return np.array([[mk.id, *mk.p, *mk.R.ravel()] for mk in mks])


def obs_rows(frames):
    return np.array([[f, ob.id, *np.asarray(ob.uv, float).ravel()] for f, fr in enumerate(frames) for ob in fr]).reshape(-1, 10)


def rec_obs(name, frames, tag='obs'):
    rec('nf', name, [len(frames)])
    rec(tag, name, obs_rows(frames))


def cp(x, y, z, yaw, roll=0.0, pitch=0.0):
    return CamPose(c=np.array([x, y, z], float), yaw=yaw, roll=roll, pitch=pitch)


