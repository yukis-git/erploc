#!/usr/bin/env python3
"""Write fixtures/typed.txt: Python outputs of the per-marker front gap (wall 0.07 m, stand 0.02 m) of `precompute_typed`, for the
differential test `oc_typed` of crates/erploc-place/tests/diff_site.rs.
Record: <tag> <name> <rows> <cols> <values...> (repr, round-trip exact). Cases: the demo room, a second room `s2` (two obstacles, two camera
heights, sector, pixel noise) and `pole` (a thin pole between camera and marker). The information blocks `I` of `demo` and `s2` are
not stored: they do not depend on the kinds, are asserted here to be bit-equal to `placement.precompute`, and the test reads them
from fixtures/place.txt (`pl_tables_demo`, `pl_tables_s2`, written by export_place_fixtures.py from the same specifications).
Set ERPLOC_PY_ROOT to the directory that contains the `erploc` Python package. Deterministic."""
import dataclasses
import os
import sys
import numpy as np

REPO = os.environ.get('ERPLOC_PY_ROOT', os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, REPO)
from erploc import placement as pl  # noqa: E402
from erploc.erp import ErpCamera  # noqa: E402
from erploc.fisher import info_marker  # noqa: E402
from erploc.jacobian import CamPose  # noqa: E402
from erploc.scene import Candidate, Obstacle, Workspace, candidates_from_walls, cells as scene_cells  # noqa: E402
from erploc.visibility import FRONT_GAP_STAND, FRONT_GAP_WALL, Sector, VisParams, visible_batch  # noqa: E402

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'fixtures', 'typed.txt')
lines = ['# generated by tools/export_typed_fixtures.py with numpy ' + np.__version__]


def rec(tag, name, a):
    a = np.asarray(a, float)
    a = a.reshape(1, 1) if a.ndim == 0 else (a.reshape(1, -1) if a.ndim == 1 else a)
    lines.append(' '.join([tag, name, str(a.shape[0]), str(a.shape[1])] + [repr(float(x)) for x in a.ravel()]))


def precompute_typed(spec, kinds):
    """`precompute` with per-marker gaps (visible_batch(..., gaps=...))."""
    xy = scene_cells(spec.ws, spec.obstacles)
    C = np.concatenate([np.column_stack([xy, np.full(len(xy), float(z))]) for z in spec.ws.z_cam], axis=0)
    mks = pl.markers_from_candidates(spec.candidates)
    gaps = np.array([FRONT_GAP_STAND if k == 'stand' else FRONT_GAP_WALL for k in kinds])
    vis = visible_batch(C, np.asarray(spec.ws.headings, float), mks, spec.A, spec.cam_model, spec.obstacles, spec.vp, True, gaps)
    K, N = len(C), len(mks)
    I = np.zeros((K, N, 4, 4))
    for k in range(K):
        cam = CamPose(c=C[k], yaw=0.0, roll=0.0, pitch=0.0)
        for j, mk in enumerate(mks):
            I[k, j] = info_marker(cam, mk, spec.A, spec.cam_model, spec.sigma_px, spec.noise_model)[0]
    return C, vis, I


CAM = ErpCamera(W=6528, H=3264)
SECA = Sector(np.deg2rad(-30.0), np.deg2rad(30.0), np.deg2rad(-90.0), np.deg2rad(90.0))
specs = {'demo': pl.demo_spec()}
ROOM_S2 = np.array([[0., 0.], [9., 0.], [9., 6.], [0., 6.]])
ws2 = Workspace(poly=np.array([[0.8, 0.8], [8.2, 0.8], [8.2, 5.2], [0.8, 5.2]]), spacing=1.0, z_cam=(1.0, 1.4),
                headings=tuple(np.pi * k / 2.0 for k in range(4)))
specs['s2'] = pl.PlacementSpec(
    ws=ws2, obstacles=(Obstacle(np.array([[2.5, 2.0], [4.0, 2.0], [4.0, 3.0], [2.5, 3.0]]), 1.5),
                       Obstacle(np.array([[6.0, 3.5], [7.0, 3.5], [7.0, 4.5], [6.0, 4.5]]), 2.5)),
    candidates=candidates_from_walls([Obstacle(poly=ROOM_S2, height=3.0)], spacing=2.0, z=1.4, offset=0.05, inward=True),
    n_max=12, A=0.16, cam_model=CAM, sigma_px=0.3, noise_model='pixel',
    vp=VisParams(psi_max=np.deg2rad(70.0), px_min=12.0, sectors=(SECA,)), tau=0.03, k_min=3, tau_loo=None,
    sigma_cap=10.0, w_k=2.5)
m = lambda az: Candidate(xy=np.array([4.0, 0.0]), z=1.5, azimuth=az)
specs['pole'] = dataclasses.replace(
    pl.demo_spec(2), ws=Workspace(poly=np.array([[-0.5, -0.5], [0.5, -0.5], [0.5, 0.5], [-0.5, 0.5]]), spacing=0.5, z_cam=(1.2,),
                                  headings=(0.0,)),
    obstacles=(Obstacle(np.array([[3.94, -1.0], [3.96, -1.0], [3.96, 1.0], [3.94, 1.0]]), 2.0),),
    candidates=[m(np.pi), m(np.pi)])
for nm, spec in specs.items():
    case = 'oc_typed_' + nm
    ws = spec.ws
    rec('wspoly', case, ws.poly)
    rec('ws', case, [ws.spacing])
    rec('zc', case, ws.z_cam)
    rec('hd', case, ws.headings)
    rec('ob', case, np.array([[i, x, y, ob.height] for i, ob in enumerate(spec.obstacles) for x, y in np.asarray(ob.poly, float)]).reshape(-1, 4))
    rec('cand', case, np.array([[*c.xy, c.z, c.azimuth] for c in spec.candidates]))
    rec('sec', case, np.array([[s.lam_min, s.lam_max, s.phi_min, s.phi_max] for s in spec.vp.sectors], float).reshape(-1, 4))
    rec('sc', case, [spec.n_max, spec.A, spec.cam_model.W, spec.cam_model.H, spec.cam_model.lam_sign, spec.sigma_px,
                     {'tangent': 0.0, 'pixel': 1.0}[spec.noise_model], spec.vp.psi_max, spec.vp.px_min, spec.vp.eps,
                     spec.tau, spec.k_min, np.nan if spec.tau_loo is None else spec.tau_loo, spec.sigma_cap, spec.w_k])
    N = len(spec.candidates)
    kinds = ['stand' if (j % 3 != 0 if nm != 'pole' else j == 0) else 'wall' for j in range(N)]
    C, vis, I = precompute_typed(spec, kinds)
    Cw, visw, _ = precompute_typed(spec, ['wall'] * N)
    K, Hd, _ = vis.shape
    rec('kinds', case, np.array([1.0 if k == 'stand' else 0.0 for k in kinds]))
    rec('cells', case, C)
    rec('vis', case, vis.reshape(K * Hd, N).astype(float))
    if nm == 'pole':
        rec('I', case, I.reshape(K * N, 16))
    else:
        tb = pl.precompute(spec)
        assert np.array_equal(tb.I, I) and np.array_equal(tb.cells, C), nm
    print(case, 'K=%d Hd=%d N=%d stands=%d; vis differs from all-wall gaps in %d (cell, heading, marker) entries'
          % (K, Hd, N, kinds.count('stand'), int((vis != visw).sum())))
with open(OUT, 'w') as f:
    f.write('\n'.join(lines) + '\n')
print('wrote', OUT, len(lines) - 1, 'records')
