#!/usr/bin/env python3
"""Write fixtures/linalg.txt: inputs and numpy 2.0.2 outputs for the Rust differential tests.
Record: <tag> <name> <rows> <cols> <values...> (repr, round-trip exact). Run with the repo .venv python."""
import os
import numpy as np

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'fixtures', 'linalg.txt')
rng = np.random.default_rng(20261004)
rng2 = np.random.default_rng(20261005)   # draws added later (keeps the original records identical)
lines = ['# generated by tools/export_linalg_fixtures.py with numpy ' + np.__version__]


def rec(tag, name, a):
    a = np.atleast_2d(np.asarray(a, float))
    lines.append(' '.join([tag, name, str(a.shape[0]), str(a.shape[1])] + [repr(float(x)) for x in a.ravel()]))


case = 0
# general square (solve / inv / det)
for n in (1, 2, 3, 4, 6, 10):
    for _ in range(3):
        a = rng.uniform(-1, 1, (n, n)) + n * np.eye(n) * rng.uniform(0, 1)
        b = rng.uniform(-1, 1, n)
        nm = 'sq%d' % case; case += 1
        rec('A', nm, a); rec('b', nm, b)
        rec('solve', nm, np.linalg.solve(a, b)); rec('inv', nm, np.linalg.inv(a)); rec('det', nm, np.linalg.det(a))
# symmetric, incl. ill-conditioned SPD like 4x4 / 6x6 Fisher matrices (condition 1e2 .. 1e14) and PSD rank-deficient
for n in (2, 3, 4, 6, 12):
    for cond in (1e2, 1e6, 1e10, 1e14):
        q, _ = np.linalg.qr(rng.normal(size=(n, n)))
        w = np.logspace(0, -np.log10(cond), n) * rng.uniform(1, 1e6)
        a = (q * w) @ q.T
        nm = 'sym%d' % case; case += 1
        rec('S', nm, a); rec('eigvalsh', nm, np.linalg.eigvalsh(a)); rec('eigvecs', nm, np.linalg.eigh(a)[1])
    j = rng.normal(size=(n - 1, n))                       # rank n-1 PSD (singular)
    nm = 'sym%d' % case; case += 1
    rec('S', nm, j.T @ j); rec('eigvalsh', nm, np.linalg.eigvalsh(j.T @ j)); rec('eigvecs', nm, np.linalg.eigh(j.T @ j)[1])
def rect_extra(nm, a):
    u, _, vt = np.linalg.svd(a)                          # full U (m×m), Vt (n×n)
    b = rng2.uniform(-1, 1, a.shape[0])
    rec('U', nm, u); rec('Vt', nm, vt)
    rec('lb', nm, b); rec('lstsq', nm, np.linalg.lstsq(a, b, rcond=None)[0])


# rectangular (svd singular values / pinv)
for (m, n) in ((8, 9), (9, 8), (3, 3), (6, 3), (2, 5), (12, 4)):
    a = rng.uniform(-1, 1, (m, n))
    nm = 'rect%d' % case; case += 1
    rec('M', nm, a); rec('sv', nm, np.linalg.svd(a, compute_uv=False)); rec('pinv', nm, np.linalg.pinv(a))
    rect_extra(nm, a)
a = np.array([[1., 2.], [2., 4.]]); nm = 'rect%d' % case
rec('M', nm, a); rec('sv', nm, np.linalg.svd(a, compute_uv=False)); rec('pinv', nm, np.linalg.pinv(a))
rect_extra(nm, a)
# large PSD: n = 100, rank 95 (5-dim null space)
j = rng2.normal(size=(95, 100))
rec('S', 'big0', j.T @ j); rec('eigvalsh', 'big0', np.linalg.eigvalsh(j.T @ j))
os.makedirs(os.path.dirname(OUT), exist_ok=True)
open(OUT, 'w').write('\n'.join(lines) + '\n')
print('wrote', OUT, len(lines) - 1, 'records')
